"""Deterministic, self-contained HTML page builder for MineM."""

from __future__ import annotations

import base64
import html
import json
import mimetypes
import re
from pathlib import Path
from typing import Any


CANVAS_WIDTH = 1920
CANVAS_HEIGHT = 1080
LAYOUTS = {"split", "statement", "metrics"}
THEMES = {
    "dark": {
        "background": "#090E1A",
        "surface": "#141B2B",
        "text": "#F7F9FC",
        "muted": "#AAB4C8",
        "border": "#2B3548",
    },
    "light": {
        "background": "#F3F6FA",
        "surface": "#FFFFFF",
        "text": "#111827",
        "muted": "#667085",
        "border": "#D7DEE8",
    },
}
DEFAULT_ACCENT = "#2F80ED"
ALLOWED_IMAGE_SUFFIXES = {".png", ".jpg", ".jpeg", ".webp", ".gif", ".svg"}
MAX_IMAGE_BYTES = 50 * 1024 * 1024


class HtmlPageBuildError(ValueError):
    """Raised when a page specification cannot be rendered safely."""


def _clean_text(value: Any, *, limit: int = 4000) -> str:
    return re.sub(r"\s+", " ", str(value or "")).strip()[:limit]


def _clean_color(value: Any) -> str:
    color = str(value or "").strip()
    if not re.fullmatch(r"#[0-9a-fA-F]{6}", color):
        return DEFAULT_ACCENT
    return color.upper()


def _string_list(value: Any, *, limit: int) -> list[str]:
    if not isinstance(value, list):
        return []
    return [_clean_text(item, limit=240) for item in value if _clean_text(item, limit=240)][:limit]


def _metric_list(value: Any) -> list[dict[str, str]]:
    if not isinstance(value, list):
        return []
    metrics = []
    for item in value[:4]:
        if not isinstance(item, dict):
            continue
        metric_value = _clean_text(item.get("value"), limit=40)
        label = _clean_text(item.get("label"), limit=80)
        if metric_value:
            metrics.append({"value": metric_value, "label": label})
    return metrics


def _image_data_uri(value: Any, base_dir: Path) -> str:
    raw = str(value or "").strip()
    if not raw:
        return ""
    if raw.startswith("data:image/"):
        raise HtmlPageBuildError("image must be a local file path; data URIs are generated by MineM")
    if re.match(r"^[a-z][a-z0-9+.-]*://", raw, flags=re.I):
        raise HtmlPageBuildError("image must be a local file so the generated HTML stays self-contained")
    image_path = Path(raw).expanduser()
    if not image_path.is_absolute():
        image_path = base_dir / image_path
    image_path = image_path.resolve()
    if not image_path.is_file():
        raise HtmlPageBuildError(f"image file does not exist: {image_path}")
    if image_path.suffix.lower() not in ALLOWED_IMAGE_SUFFIXES:
        raise HtmlPageBuildError(f"unsupported image type: {image_path.suffix or 'unknown'}")
    if image_path.stat().st_size > MAX_IMAGE_BYTES:
        raise HtmlPageBuildError("image exceeds the 50 MB self-contained page limit")
    mime = mimetypes.guess_type(image_path.name)[0] or "application/octet-stream"
    encoded = base64.b64encode(image_path.read_bytes()).decode("ascii")
    return f"data:{mime};base64,{encoded}"


def normalize_page_spec(spec: dict[str, Any], *, base_dir: Path) -> dict[str, Any]:
    if not isinstance(spec, dict):
        raise HtmlPageBuildError("page specification must be a JSON object")
    title = _clean_text(spec.get("title"), limit=180)
    if not title:
        raise HtmlPageBuildError("title is required")
    theme_name = str(spec.get("theme") or "dark").strip().lower()
    if theme_name not in THEMES:
        raise HtmlPageBuildError(f"theme must be one of: {', '.join(sorted(THEMES))}")
    layout = str(spec.get("layout") or "split").strip().lower()
    if layout not in LAYOUTS:
        raise HtmlPageBuildError(f"layout must be one of: {', '.join(sorted(LAYOUTS))}")
    body_value = spec.get("body")
    if isinstance(body_value, list):
        body = [_clean_text(item, limit=700) for item in body_value if _clean_text(item, limit=700)][:4]
    else:
        cleaned = _clean_text(body_value, limit=2400)
        body = [cleaned] if cleaned else []
    return {
        "title": title,
        "eyebrow": _clean_text(spec.get("eyebrow"), limit=80),
        "subtitle": _clean_text(spec.get("subtitle"), limit=320),
        "body": body,
        "bullets": _string_list(spec.get("bullets"), limit=6),
        "metrics": _metric_list(spec.get("metrics")),
        "image": _image_data_uri(spec.get("image"), base_dir),
        "imageAlt": _clean_text(spec.get("imageAlt"), limit=120) or title,
        "source": _clean_text(spec.get("source"), limit=220),
        "footer": _clean_text(spec.get("footer"), limit=160),
        "layout": layout,
        "theme": theme_name,
        "accent": _clean_color(spec.get("accent")),
    }


def _render_body(paragraphs: list[str]) -> str:
    return "".join(f"<p>{html.escape(paragraph)}</p>" for paragraph in paragraphs)


def _render_bullets(items: list[str]) -> str:
    if not items:
        return ""
    return "<ul>" + "".join(f"<li>{html.escape(item)}</li>" for item in items) + "</ul>"


def _render_metrics(items: list[dict[str, str]]) -> str:
    if not items:
        return ""
    blocks = []
    for item in items:
        blocks.append(
            '<div class="metric">'
            f'<strong>{html.escape(item["value"])}</strong>'
            f'<span>{html.escape(item["label"])}</span>'
            "</div>"
        )
    return '<div class="metrics">' + "".join(blocks) + "</div>"


