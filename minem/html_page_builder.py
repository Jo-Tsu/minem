def render_page_html(spec: dict[str, Any], *, base_dir: Path | None = None) -> str:
    normalized = normalize_page_spec(spec, base_dir=(base_dir or Path.cwd()).resolve())
    return _render_normalized_page(normalized)


def build_page_file(spec_path: Path, output_path: Path | None = None) -> tuple[Path, dict[str, Any]]:
    source = Path(spec_path).expanduser().resolve()
    if not source.is_file():
        raise HtmlPageBuildError(f"spec file does not exist: {source}")
    try:
        raw = json.loads(source.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as error:
        raise HtmlPageBuildError(f"cannot read page specification: {error}") from error
    normalized = normalize_page_spec(raw, base_dir=source.parent)
    output = Path(output_path).expanduser().resolve() if output_path else source.with_suffix(".html")
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(_render_normalized_page(normalized), encoding="utf-8")
    return output, normalized
